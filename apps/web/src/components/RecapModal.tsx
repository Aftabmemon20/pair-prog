"use client";

import React, { useState, useEffect } from "react";
import {
  FileText,
  CheckCircle,
  Copy,
  Check,
  X,
  Loader2,
  Bug,
  Shield,
  Layers,
  ArrowRight,
  Sparkles,
} from "lucide-react";

export interface BugRecord {
  symbol: string;
  error_type: string;
  error_message: string;
  owner?: string;
  resolution?: string;
}

export interface OwnershipSummaryItem {
  symbol: string;
  owner: string;
  status: string;
}

export interface SessionRecap {
  id?: string;
  session_id: string;
  summary: string;
  decisions: string[];
  ownership_summary: OwnershipSummaryItem[];
  bugs_identified: BugRecord[];
  next_steps: string[];
}

interface RecapModalProps {
  roomId: string;
  isOpen: boolean;
  onClose: () => void;
}

export function RecapModal({ roomId, isOpen, onClose }: RecapModalProps) {
  const [recap, setRecap] = useState<SessionRecap | null>(null);
  const [isLoading, setIsLoading] = useState<boolean>(true);
  const [copied, setCopied] = useState<boolean>(false);

  useEffect(() => {
    if (!isOpen || !roomId) return;

    setIsLoading(true);
    const apiUrl = process.env.NEXT_PUBLIC_API_URL || "http://localhost:8000";

    fetch(`${apiUrl}/rooms/${roomId}/recap`, { method: "POST" })
      .then((res) => (res.ok ? res.json() : null))
      .then((data) => {
        if (data) setRecap(data);
      })
      .catch((err) => console.error("Error generating recap:", err))
      .finally(() => setIsLoading(false));
  }, [isOpen, roomId]);

  const handleCopyMarkdown = async () => {
    if (!roomId) return;
    try {
      const apiUrl = process.env.NEXT_PUBLIC_API_URL || "http://localhost:8000";
      const res = await fetch(`${apiUrl}/rooms/${roomId}/recap/markdown`);
      if (res.ok) {
        const text = await res.text();
        await navigator.clipboard.writeText(text);
        setCopied(true);
        setTimeout(() => setCopied(false), 2000);
      }
    } catch (err) {
      console.error("Failed to copy markdown:", err);
    }
  };

  if (!isOpen) return null;

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-950/80 backdrop-blur-md animate-in fade-in duration-200">
      <div className="bg-slate-900 border border-slate-800 rounded-xl max-w-2xl w-full max-h-[85vh] flex flex-col shadow-2xl overflow-hidden">
        {/* Header */}
        <div className="px-5 py-4 border-b border-slate-800 flex items-center justify-between bg-slate-900/90">
          <div className="flex items-center gap-2.5">
            <div className="w-8 h-8 rounded-lg bg-gradient-to-tr from-purple-600 to-indigo-500 flex items-center justify-center text-white shadow-md shadow-purple-600/20">
              <Sparkles className="w-4 h-4" />
            </div>
            <div>
              <h2 className="text-sm font-bold text-slate-100 flex items-center gap-2">
                Pairio-Lite Session Recap
                <span className="text-[11px] font-mono px-2 py-0.5 rounded bg-slate-800 text-purple-300 border border-slate-700/60 font-normal">
                  room: {roomId}
                </span>
              </h2>
              <p className="text-[11px] text-slate-400">
                Automated session summary generated by Pair Master (Seat 3 AI)
              </p>
            </div>
          </div>

          <button
            onClick={onClose}
            className="p-1.5 text-slate-400 hover:text-slate-200 hover:bg-slate-800 rounded-lg transition"
          >
            <X className="w-4 h-4" />
          </button>
        </div>

        {/* Content */}
        <div className="flex-1 overflow-y-auto p-5 space-y-5 text-xs text-slate-300">
          {isLoading ? (
            <div className="flex flex-col items-center justify-center py-16 space-y-3">
              <Loader2 className="w-7 h-7 animate-spin text-purple-400" />
              <p className="font-medium text-slate-300">Synthesizing Session Recap...</p>
              <p className="text-[11px] text-slate-500">
                Aggregating AST ownership, bug resolutions, and decisions
              </p>
            </div>
          ) : recap ? (
            <>
              {/* Executive Summary */}
              <div className="p-3.5 bg-purple-950/20 border border-purple-800/40 rounded-lg leading-relaxed text-slate-200">
                <span className="font-semibold text-purple-300 uppercase tracking-wider text-[10px] block mb-1">
                  Executive Summary
                </span>
                {recap.summary}
              </div>

              {/* Key Decisions */}
              {recap.decisions.length > 0 && (
                <div className="space-y-2">
                  <span className="font-semibold uppercase text-slate-400 text-[11px] tracking-wider flex items-center gap-1.5">
                    <CheckCircle className="w-3.5 h-3.5 text-emerald-400" />
                    Key Architectural Decisions:
                  </span>
                  <div className="space-y-1.5 pl-2">
                    {recap.decisions.map((dec, idx) => (
                      <div key={idx} className="flex items-start gap-2">
                        <span className="text-purple-400 font-bold">•</span>
                        <span>{dec}</span>
                      </div>
                    ))}
                  </div>
                </div>
              )}

              {/* Ownership Breakdown */}
              {recap.ownership_summary.length > 0 && (
                <div className="space-y-2">
                  <span className="font-semibold uppercase text-slate-400 text-[11px] tracking-wider flex items-center gap-1.5">
                    <Layers className="w-3.5 h-3.5 text-sky-400" />
                    Code Ownership Allocation:
                  </span>
                  <div className="grid grid-cols-1 sm:grid-cols-2 gap-2">
                    {recap.ownership_summary.map((item, idx) => (
                      <div
                        key={idx}
                        className="p-2 bg-slate-950 border border-slate-800 rounded-md flex items-center justify-between"
                      >
                        <span className="font-mono text-purple-300 font-medium">
                          {item.symbol}
                        </span>
                        <span
                          className={`text-[10px] font-bold px-2 py-0.5 rounded ${
                            item.owner === "Dev A"
                              ? "bg-emerald-950/60 text-emerald-300 border border-emerald-800/60"
                              : "bg-sky-950/60 text-sky-300 border border-sky-800/60"
                          }`}
                        >
                          {item.owner}
                        </span>
                      </div>
                    ))}
                  </div>
                </div>
              )}

              {/* Bugs Identified & Resolved */}
              {recap.bugs_identified.length > 0 && (
                <div className="space-y-2">
                  <span className="font-semibold uppercase text-slate-400 text-[11px] tracking-wider flex items-center gap-1.5">
                    <Bug className="w-3.5 h-3.5 text-rose-400" />
                    Bugs Isolated:
                  </span>
                  <div className="space-y-2">
                    {recap.bugs_identified.map((bug, idx) => (
                      <div
                        key={idx}
                        className="p-3 bg-rose-950/20 border border-rose-900/40 rounded-lg space-y-1"
                      >
                        <div className="flex items-center justify-between text-[11px]">
                          <span className="font-mono font-bold text-rose-300">
                            {bug.symbol} ({bug.error_type})
                          </span>
                          <span className="text-[10px] text-slate-400">
                            Owner: <strong className="text-slate-200">{bug.owner}</strong>
                          </span>
                        </div>
                        <p className="text-slate-400 font-mono text-[11px]">
                          {bug.error_message}
                        </p>
                        {bug.resolution && (
                          <p className="text-emerald-400 text-[11px] pt-1 border-t border-rose-900/30">
                            ✓ {bug.resolution}
                          </p>
                        )}
                      </div>
                    ))}
                  </div>
                </div>
              )}

              {/* Next Steps */}
              {recap.next_steps.length > 0 && (
                <div className="space-y-2">
                  <span className="font-semibold uppercase text-slate-400 text-[11px] tracking-wider flex items-center gap-1.5">
                    <ArrowRight className="w-3.5 h-3.5 text-purple-400" />
                    Recommended Next Steps:
                  </span>
                  <div className="space-y-1.5 pl-2">
                    {recap.next_steps.map((step, idx) => (
                      <div key={idx} className="flex items-start gap-2">
                        <span className="text-emerald-400 font-bold">[ ]</span>
                        <span>{step}</span>
                      </div>
                    ))}
                  </div>
                </div>
              )}
            </>
          ) : (
            <div className="text-slate-500 py-8 text-center italic">
              No session data available to recap.
            </div>
          )}
        </div>

        {/* Footer Actions */}
        <div className="p-3 bg-slate-900/90 border-t border-slate-800 flex items-center justify-between">
          <button
            onClick={handleCopyMarkdown}
            disabled={!recap || isLoading}
            className="flex items-center gap-1.5 px-3 py-1.5 bg-slate-800 hover:bg-slate-700 text-slate-200 text-xs font-medium rounded-lg border border-slate-700/60 transition disabled:opacity-40"
            title="Copy as Markdown for Slack, Jira, or PR description"
          >
            {copied ? (
              <>
                <Check className="w-3.5 h-3.5 text-emerald-400" />
                <span className="text-emerald-300">Copied to Clipboard!</span>
              </>
            ) : (
              <>
                <Copy className="w-3.5 h-3.5 text-slate-400" />
                <span>Copy Summary (Markdown)</span>
              </>
            )}
          </button>

          <button
            onClick={onClose}
            className="px-4 py-1.5 bg-purple-600 hover:bg-purple-500 text-white font-semibold text-xs rounded-lg transition shadow-sm"
          >
            Done
          </button>
        </div>
      </div>
    </div>
  );
}
